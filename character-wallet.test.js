const assert = require("node:assert/strict");
require("fake-indexeddb/auto");
const Dexie = require("dexie");
const identity = require("./player-identity.js"), core = require("./character-wallet-core.js");
global.ephoneCharacterWalletCore = core;
global.ephonePlayerIdentity = identity;
global.ephoneSpectatorMoney = require("./spectator-money.js");
const spaceWallet = require("./space-wallet.js");
const at = (month, day, hour = 8) => new Date(2026, month - 1, day, hour).getTime();
const profile = (balance, rules = []) => ({ balance, otherAssets: 100000, job: "医生", family: "普通家庭", automatic: true, rules });
(async () => {
  const db = new Dexie("character-wallet-test-" + Date.now());
  db.version(53).stores({ chats: "&id", npcs: "++id", spaceProfiles: "&id", userWallet: "&id", userTransactions: "++id,timestamp,type", characterWallets: "&key", characterTransactions: "&id,key,vts,category" });
  try {
    await db.open();
    const members = ["甲", "乙", "丙"].map((name, i) => ({ id: "r" + i, originalName: name }));
    await db.chats.bulkPut(members.map((m) => ({ id: m.id, name: m.originalName, settings: { aiPersona: "学生，普通家庭，节俭" }, history: [] })));
    await db.chats.put({ id: "g", isGroup: true, isSpectatorGroup: true, members, history: [] });
    await db.userWallet.put({ id: "main", balance: 80, fundHoldings: ["preserved"] });
    const s = new core.Service(db), key = "chat:r0";
    assert.equal((await s.account(key)).configured, false);
    const rules = [{ id: "salary", direction: "income", cadence: "monthly", day: 31, hour: 9, min: 1000, max: 1000, label: "工资", category: "salary" },
      { id: "meal", direction: "expense", cadence: "daily", day: 1, hour: 20, min: 10, max: 30, label: "餐食" }];
    await s.save(key, profile(100, rules), at(1, 30), 0);
    assert.equal((await s.account(key)).balance, 100);
    const before = await db.characterWallets.get(key), preview = await s.settle(at(2, 28, 21), { preview: true });
    assert.deepEqual(await db.characterWallets.get(key), before, "preview cannot post future wages on a failed reply");
    assert.equal(preview.entries.filter((e) => e.category === "salary").length, 2, "31st clamps to February last day");
    const settled = await s.settle(at(2, 28, 21));
    assert.deepEqual(settled.projected, preview.projected);
    assert.ok(settled.entries.filter((e) => e.description === "餐食").every((e) => e.amount >= 10 && e.amount <= 30));
    assert.ok(new Set(settled.entries.filter((e) => e.description === "餐食").map((e) => e.amount)).size > 2);
    const count = await db.characterTransactions.count();
    await s.settle(at(2, 28, 21)); await s.settle(at(1, 31));
    assert.equal(await db.characterTransactions.count(), count, "same/reloaded/backwards time cannot pay twice");
    await assert.rejects(s.save(key, profile(50), at(2, 28, 21), before.revision), /另一处更新/);
    const limited = await s.settle(at(10, 1), { maxDays: 2 }); assert.equal(limited.pending, true);
    for (let i = 0; i < 4; i++) if (!(await s.settle(at(10, 1))).pending) break;
    assert.equal((await s.settle(at(10, 1))).pending, false);
    assert.equal((await db.characterTransactions.toArray()).filter((e) => e.category === "salary").length, 9);
    // All cents and wallet metadata are preserved; independent roles cannot spend each other's balance.
    await s.save("chat:r1", profile(5), at(10, 1), 0);
    await assert.rejects(s.book("chat:r1", 5.01, "expense", { id: "too-much", vts: at(10, 1) }), /不足/);
    const small = { id: "small", vts: at(10, 1) };
    await Promise.all([s.book("chat:r1", 0.1, "expense", small), s.book("chat:r1", 0.1, "expense", small)]);
    assert.equal((await s.account("chat:r1")).balance, 4.9);
    await db.spaceProfiles.put({ id: "player", key: "chat:r1" });
    assert.equal((await s.account("chat:r1")).balance, 80);
    await s.book("chat:r1", 10, "income", { id: "bound-income", vts: at(10, 1) });
    assert.equal((await db.userWallet.get("main")).balance, 90);
    assert.deepEqual((await db.userWallet.get("main")).fundHoldings, ["preserved"]);
    assert.equal((await s.ledger("chat:r1", Infinity)).filter((e) => e.id === "bound-income" || e.characterEntryId === "bound-income").length, 1);
    await db.spaceProfiles.delete("player"); assert.equal((await s.account("chat:r1")).balance, 4.9, "unbinding must not clone the space wallet");
    await db.spaceProfiles.put({ id: "player", key: "chat:r1" });
    // Sender debit + pending card is atomic; recipient credits the actual role, bound player credits main.
    await s.save("chat:r2", profile(500), at(10, 1), 0);
    let chat = await db.chats.get("g");
    const card = { type: "transfer", senderName: "丙", receiverName: "乙", amount: 12.34, timestamp: 700, vts: at(10, 1) };
    await s.reserveCard(chat, card); chat.history.push(card); await db.chats.put(chat);
    assert.equal((await s.account("chat:r2")).balance, 487.66);
    await s.reserveCard(chat, card); assert.equal((await s.account("chat:r2")).balance, 487.66);
    const receive = (c, t, who) => global.ephoneSpectatorMoney.receive(c, t, who, { now: t + 1, vts: at(10, 1), save: (candidate, receipt) => spaceWallet.creditReceipt(db, candidate, receipt, "default") });
    const receipt = await receive(chat, 700, "乙");
    assert.equal(receipt.walletDestination, "chat:r1"); assert.equal((await db.userWallet.get("main")).balance, 102.34);
    await assert.rejects(receive(chat, 700, "乙"));
    const other = { ...card, receiverName: "甲", timestamp: 800, walletFunded: undefined };
    await s.reserveCard(chat, other); chat.history.push(other); await db.chats.put(chat);
    const ownBefore = (await s.account(key)).balance;
    await receive(chat, 800, "甲"); assert.equal((await s.account(key)).balance, Math.round((ownBefore + 12.34) * 100) / 100);
    assert.equal((await db.userWallet.get("main")).balance, 102.34);
    const edited = { ...card, timestamp: 900, receiverName: "乙", walletFunded: undefined };
    await s.reserveCard(chat, edited); edited.amount = 100; chat.history.push(edited); await db.chats.put(chat);
    await assert.rejects(receive(chat, 900, "乙"), /金额或付款角色被改动/);
    assert.equal((await db.userWallet.get("main")).balance, 102.34);
    // A failure after the first write must roll the entire settlement back.
    const originalAdd = s.characterTransactions.add;
    s.characterTransactions.add = async () => { throw new Error("fixture write failure"); };
    const balance = (await s.account(key)).balance;
    await assert.rejects(s.book(key, 10, "income", { id: "fail", vts: at(10, 1) }), /fixture/);
    s.characterTransactions.add = originalAdd; assert.equal((await s.account(key)).balance, balance);
    const failedCard = { ...card, timestamp: 1000, walletFunded: undefined };
    const hook = db.chats.hook("updating", () => { throw new Error("card write failure"); });
    const senderBefore = (await s.account("chat:r2")).balance;
    await assert.rejects(s.reserveCard(await db.chats.get("g"), failedCard), /card write failure/);
    db.chats.hook("updating").unsubscribe(hook);
    assert.equal(failedCard.walletFunded, undefined); assert.equal((await s.account("chat:r2")).balance, senderBefore);
    assert.match(await s.prompt(await db.chats.get("g"), at(10, 1)), /每个角色只直接知道自己的资产/);
    assert.match(core.profilePrompt([{ key, name: "甲", persona: "医生，节俭，普通家庭" }]), /职业.*学生|学生.*工资/);
    assert.throws(() => core.normalize(profile(-1)), /金额无效/);
    assert.throws(() => core.normalize(profile(5, [{ ...rules[0], min: 10, max: 1 }])), /范围无效/);
    console.log("PASS: independent/bound balances, assets, recurring pay/spend, real calendar, preview rollback, deterministic cents, backwards/reload dedupe, chunked jumps, concurrency, atomic funding/receipt, edited card protection and persona-grounded plans");
  } finally { db.close(); await Dexie.delete(db.name); }
})().catch((error) => { console.error(error); process.exitCode = 1; });

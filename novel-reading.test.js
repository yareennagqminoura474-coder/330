const assert = require("node:assert/strict"), reading = require("./novel-reading.js"), chapters = require("./novel-chapters.js");
const book = { id: 1, chapters: [1, 2, 3].map(timestamp => ({ title: "标题" + timestamp, content: "正文" + timestamp, timestamp })), lastUpdated: 10 };
const position = { chapterIndex: 1, chapterSignature: reading.signature(book.chapters[1]), scrollTop: 340, ratio: .4, scrollHeight: 1400, updatedAt: 5 };
book.readingPosition = position;
assert.equal(reading.signature({ ...book.chapters[1], title: "新标题" }), position.chapterSignature);
const removed = chapters.remove(book, 0, 20);
assert.equal(removed.readingPosition.chapterIndex, 0); assert.equal(removed.readingPosition.scrollTop, 340);
assert.equal(reading.resolve(removed.chapters, position).chapterIndex, 0);
const currentRemoved = chapters.remove(book, 1, 30);
assert.equal(currentRemoved.readingPosition.chapterIndex, 1); assert.equal(currentRemoved.readingPosition.scrollTop, 0);
assert.equal(currentRemoved.readingPosition.chapterSignature, null); assert.ok(currentRemoved.readingPosition.updatedAt > position.updatedAt);
const edited = chapters.edit(book, 1, { content: "新的正文" }, 40);
assert.equal(edited.readingPosition.chapterSignature, null); assert.equal(edited.readingPosition.ratio, .4);
assert.equal(reading.resolve(edited.chapters, edited.readingPosition).chapterIndex, 1);
assert.equal(chapters.edit(book, 1, { title: "改标题" }, 50).readingPosition, position);
assert.equal(chapters.remove({ ...book, chapters: [book.chapters[0]] }, 0).readingPosition, null);
assert.deepEqual(reading.resolve([], position), { chapterIndex: 0, bookmark: null });
assert.equal(reading.resolve(book.chapters, { ...position, chapterIndex: 99 }).chapterIndex, 1);
assert.equal(reading.resolve(book.chapters, { ...position, chapterSignature: "gone" }).bookmark.scrollTop, 0);
assert.equal(book.readingPosition.scrollTop, 340); assert.equal(book.chapters.length, 3);
const prose = '早上他先说：“早上好。”\n争执到最后，他问：“如果这次我不回头，你还会等我吗？”她没有回答。';
assert.equal(chapters.chooseTitle(prose, "你还会等我吗？"), "你还会等我吗？", "preserve a meaningful literal clause chosen with full chapter context");
console.log("PASS: per-chapter bookmark identity, edits/deletions/reindexing, changed text/reflow fallback, immutable metadata and representative source-title excerpts");
